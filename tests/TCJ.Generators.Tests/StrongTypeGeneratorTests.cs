    [Fact]
    public void GuidStrongId_CompilesAndExecutes_ValueDefaultEqualityHashingAndToString()
    {
        var compilation = CreateCompilation(
            AttributeSource,
            """
            using System;
            using TCJ.Core.StrongTypes;

            [StronglyTypedId<Guid>]
            public readonly partial record struct OrderId;
            """);

        var result = RunGenerator(compilation);
        Assert.Empty(result.OutputCompilation.GetDiagnostics().Where(static diagnostic => diagnostic.Severity == DiagnosticSeverity.Error));

        var assembly = EmitAndLoad(result.OutputCompilation);
        var orderIdType = assembly.GetType("OrderId");
        Assert.NotNull(orderIdType);
        var valueProperty = orderIdType.GetProperty("Value");
        var isDefaultProperty = orderIdType.GetProperty("IsDefault");
        Assert.NotNull(valueProperty);
        Assert.NotNull(isDefaultProperty);
        Assert.False(valueProperty.CanWrite);
        var value = Guid.Parse("7a29be31-268d-4f2b-babc-fce0ce1cb46c");
        var differentValue = Guid.Parse("a7ef2a4f-4dde-42ee-b17c-0ea2f3c58996");

        var first = Activator.CreateInstance(orderIdType, value);
        var second = Activator.CreateInstance(orderIdType, value);
        var different = Activator.CreateInstance(orderIdType, differentValue);
        var defaultId = Activator.CreateInstance(orderIdType);
        Assert.NotNull(first);
        Assert.NotNull(second);
        Assert.NotNull(different);
        Assert.NotNull(defaultId);

        Assert.Equal(value, valueProperty.GetValue(first));
        Assert.False(Assert.IsType<bool>(isDefaultProperty.GetValue(first)));
        Assert.Equal(Guid.Empty, valueProperty.GetValue(defaultId));
        Assert.True(Assert.IsType<bool>(isDefaultProperty.GetValue(defaultId)));
        Assert.Equal(first, second);
        Assert.Equal(first.GetHashCode(), second.GetHashCode());
        Assert.NotEqual(first, different);
        Assert.Equal(value.ToString("D"), first.ToString());
    }


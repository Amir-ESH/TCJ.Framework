    private static GeneratorResult RunGenerator(CSharpCompilation compilation)
    {
        GeneratorDriver driver = CSharpGeneratorDriver.Create(new StrongTypeGenerator());

        driver = driver.RunGeneratorsAndUpdateCompilation(
            compilation,
            out var outputCompilation,
            out var diagnostics);

        var runResult = driver.GetRunResult();
        var generatedSources = runResult.Results
            .Where(static result => !result.GeneratedSources.IsDefault)
            .SelectMany(static result => result.GeneratedSources)
            .Select(static source => new GeneratedSource(source.HintName, source.SourceText.ToString()))
            .OrderBy(static source => source.HintName, StringComparer.Ordinal)
            .ToArray();

        var generatorException = Assert.Single(runResult.Results).Exception;

        return new GeneratorResult(
            diagnostics,
            generatedSources,
            (CSharpCompilation)outputCompilation,
            generatorException);
    }

    private static CSharpCompilation CreateCompilation(params string[] sources)
    {
        var parseOptions = new CSharpParseOptions(LanguageVersion.Latest);
        var syntaxTrees = sources
            .Append(GuidGeneratorContractSource)
            .Append(ResultContractSource)
            .Select(source => CSharpSyntaxTree.ParseText(source, parseOptions))
            .ToArray();

        return CSharpCompilation.Create(
            "Test_" + Guid.NewGuid().ToString("N"),
            syntaxTrees,
            TrustedPlatformReferences,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));
    }

    private static Assembly EmitAndLoad(CSharpCompilation compilation)
    {
        using var stream = new MemoryStream();
        var emitResult = compilation.Emit(stream);
        Assert.True(
            emitResult.Success,
            string.Join(Environment.NewLine, emitResult.Diagnostics.Select(static diagnostic => diagnostic.ToString())));

        return Assembly.Load(stream.ToArray());
    }


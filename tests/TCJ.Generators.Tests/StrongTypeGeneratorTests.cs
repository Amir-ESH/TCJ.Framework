    [Fact]
    public void NumericStrongIds_RoundTripBoundariesOverflowAndInvariantFormatting()
    {
        var compilation = CreateCompilation(
            AttributeSource,
            """
            using System;
            using System.Globalization;
            using TCJ.Core.StrongTypes;

            [StronglyTypedId<int>]
            public readonly partial record struct IntId;

            [StronglyTypedId<long>]
            public readonly partial record struct LongId;

            public static class NumericStrongIdProbe
            {
                public static bool Verify()
                {
                    var previousCulture = CultureInfo.CurrentCulture;
                    var previousUiCulture = CultureInfo.CurrentUICulture;

                    try
                    {
                        CultureInfo.CurrentCulture = new CultureInfo("fa-IR");
                        CultureInfo.CurrentUICulture = new CultureInfo("fa-IR");

                        if (!VerifyInt(int.MinValue) ||
                            !VerifyInt(-42) ||
                            !VerifyInt(0) ||
                            !VerifyInt(int.MaxValue) ||
                            !VerifyLong(long.MinValue) ||
                            !VerifyLong(-42L) ||
                            !VerifyLong(0L) ||
                            !VerifyLong(long.MaxValue))
                        {
                            return false;
                        }

                        var formattedInt = (IntId)1234567;
                        var formattedLong = (LongId)1234567890123L;
                        if (!string.Equals(formattedInt.ToString("N0", CultureInfo.CurrentCulture), "1,234,567", StringComparison.Ordinal) ||
                            !string.Equals(formattedLong.ToString("N0", CultureInfo.CurrentCulture), "1,234,567,890,123", StringComparison.Ordinal))
                        {
                            return false;
                        }

                        if (IntId.TryParse("1,234", CultureInfo.CurrentCulture, out _) ||
                            LongId.TryParse("1,234", CultureInfo.CurrentCulture, out _))
                        {
                            return false;
                        }

                        if (IntId.TryParse("2147483648", out var intOverflow) || !intOverflow.IsDefault ||
                            LongId.TryParse("9223372036854775808", out var longOverflow) || !longOverflow.IsDefault)
                        {
                            return false;
                        }

                        try
                        {
                            _ = IntId.Parse("2147483648");
                            return false;
                        }
                        catch (OverflowException)
                        {
                        }

                        try
                        {
                            _ = LongId.Parse("9223372036854775808");
                            return false;
                        }
                        catch (OverflowException)
                        {
                        }

                        return true;
                    }
                    finally
                    {
                        CultureInfo.CurrentCulture = previousCulture;
                        CultureInfo.CurrentUICulture = previousUiCulture;
                    }
                }

                private static bool VerifyInt(int value)
                {
                    var id = (IntId)value;
                    var expected = value.ToString(null, CultureInfo.InvariantCulture);
                    if ((int)id != value ||
                        id.Value != value ||
                        id.IsDefault != (value == 0) ||
                        !string.Equals(id.ToString(), expected, StringComparison.Ordinal) ||
                        IntId.Parse(expected, CultureInfo.CurrentCulture) != id ||
                        IntId.Parse(expected.AsSpan(), CultureInfo.CurrentCulture) != id ||
                        !IntId.TryParse(expected, CultureInfo.CurrentCulture, out var parsed) ||
                        parsed != id)
                    {
                        return false;
                    }

                    Span<char> buffer = stackalloc char[32];
                    if (!id.TryFormat(buffer, out var charsWritten, default, CultureInfo.CurrentCulture))
                    {
                        return false;
                    }

                    return string.Equals(new string(buffer[..charsWritten]), expected, StringComparison.Ordinal);
                }

                private static bool VerifyLong(long value)
                {
                    var id = (LongId)value;
                    var expected = value.ToString(null, CultureInfo.InvariantCulture);
                    if ((long)id != value ||
                        id.Value != value ||
                        id.IsDefault != (value == 0L) ||
                        !string.Equals(id.ToString(), expected, StringComparison.Ordinal) ||
                        LongId.Parse(expected, CultureInfo.CurrentCulture) != id ||
                        LongId.Parse(expected.AsSpan(), CultureInfo.CurrentCulture) != id ||
                        !LongId.TryParse(expected.AsSpan(), CultureInfo.CurrentCulture, out var parsed) ||
                        parsed != id)
                    {
                        return false;
                    }

                    Span<char> buffer = stackalloc char[32];
                    if (!id.TryFormat(buffer, out var charsWritten, default, CultureInfo.CurrentCulture))
                    {
                        return false;
                    }

                    return string.Equals(new string(buffer[..charsWritten]), expected, StringComparison.Ordinal);
                }
            }
            """);

        var result = RunGenerator(compilation);
        Assert.Empty(result.GeneratorDiagnostics);
        Assert.Empty(result.OutputCompilation.GetDiagnostics().Where(static diagnostic => diagnostic.Severity == DiagnosticSeverity.Error));

        var assembly = EmitAndLoad(result.OutputCompilation);
        var probeType = Assert.IsAssignableFrom<Type>(assembly.GetType("NumericStrongIdProbe"));
        var verify = Assert.IsAssignableFrom<MethodInfo>(probeType.GetMethod("Verify", BindingFlags.Public | BindingFlags.Static));

        Assert.True(Assert.IsType<bool>(verify.Invoke(null, null)));
    }


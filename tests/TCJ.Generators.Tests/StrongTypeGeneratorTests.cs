    [Fact]
    public void GuidStrongId_ParsesFormatsAndExplicitlyConverts_WithStableInvariantWireSemantics()
    {
        var compilation = CreateCompilation(
            AttributeSource,
            """
            using System;
            using System.Globalization;
            using TCJ.Core.StrongTypes;

            [StronglyTypedId<Guid>]
            public readonly partial record struct OrderId;

            public static class StrongIdProbe
            {
                public static bool Verify()
                {
                    var previousCulture = CultureInfo.CurrentCulture;
                    var previousUiCulture = CultureInfo.CurrentUICulture;

                    try
                    {
                        CultureInfo.CurrentCulture = new CultureInfo("fa-IR");
                        CultureInfo.CurrentUICulture = new CultureInfo("fa-IR");

                        var value = Guid.Parse("7a29be31-268d-4f2b-babc-fce0ce1cb46c");
                        var expectedText = value.ToString("D", CultureInfo.InvariantCulture);
                        var id = (OrderId)value;

                        if ((Guid)id != value || id.Value != value)
                        {
                            return false;
                        }

                        if (!string.Equals(id.ToString(), expectedText, StringComparison.Ordinal))
                        {
                            return false;
                        }

                        if (!string.Equals(id.ToString(null, CultureInfo.CurrentCulture), expectedText, StringComparison.Ordinal))
                        {
                            return false;
                        }

                        var parsed = OrderId.Parse(expectedText);
                        var parsedWithProvider = OrderId.Parse(expectedText, CultureInfo.CurrentCulture);
                        var parsedFromSpan = OrderId.Parse(expectedText.AsSpan(), CultureInfo.CurrentCulture);
                        if (parsed != id || parsedWithProvider != id || parsedFromSpan != id)
                        {
                            return false;
                        }

                        if (!OrderId.TryParse(expectedText, out var tryParsed) || tryParsed != id)
                        {
                            return false;
                        }

                        if (!OrderId.TryParse(expectedText.AsSpan(), CultureInfo.CurrentCulture, out var spanParsed) || spanParsed != id)
                        {
                            return false;
                        }

                        if (OrderId.TryParse("not-a-guid", out var invalid) || !invalid.IsDefault)
                        {
                            return false;
                        }

                        if (OrderId.TryParse(null, out var nullInput) || !nullInput.IsDefault)
                        {
                            return false;
                        }

                        if (OrderId.TryParse(value.ToString("N"), out _))
                        {
                            return false;
                        }

                        try
                        {
                            _ = OrderId.Parse("not-a-guid");
                            return false;
                        }
                        catch (FormatException)
                        {
                        }

                        Span<char> buffer = stackalloc char[36];
                        if (!id.TryFormat(buffer, out var charsWritten) || charsWritten != 36)
                        {
                            return false;
                        }

                        if (!string.Equals(new string(buffer[..charsWritten]), expectedText, StringComparison.Ordinal))
                        {
                            return false;
                        }

                        Span<char> tooSmall = stackalloc char[35];
                        if (id.TryFormat(tooSmall, out _))
                        {
                            return false;
                        }

                        return true;
                    }
                    finally
                    {
                        CultureInfo.CurrentCulture = previousCulture;
                        CultureInfo.CurrentUICulture = previousUiCulture;
                    }
                }
            }
            """);

        var result = RunGenerator(compilation);
        Assert.Empty(result.OutputCompilation.GetDiagnostics().Where(static diagnostic => diagnostic.Severity == DiagnosticSeverity.Error));

        var assembly = EmitAndLoad(result.OutputCompilation);
        var probeType = Assert.IsAssignableFrom<Type>(assembly.GetType("StrongIdProbe"));
        var verify = Assert.IsAssignableFrom<MethodInfo>(probeType.GetMethod("Verify", BindingFlags.Public | BindingFlags.Static));

        Assert.True(Assert.IsType<bool>(verify.Invoke(null, null)));
    }

    [Fact]
    public void GuidStrongId_CreationHelpersUseInjectedGeneratorPreserveExactValuesAndGuardNull()
    {
        var compilation = CreateCompilation(
            AttributeSource,
            """
            using System;
            using TCJ.Core.Identifiers;
            using TCJ.Core.StrongTypes;

            [StronglyTypedId<Guid>]
            public readonly partial record struct OrderId;

            public sealed class FakeGuidGenerator : IGuidGenerator
            {
                private readonly Guid _version4;
                private readonly Guid _version7;

                public FakeGuidGenerator(Guid version4, Guid version7)
                {
                    _version4 = version4;
                    _version7 = version7;
                }

                public int CreateCalls { get; private set; }

                public int CreateVersion7Calls { get; private set; }

                public Guid Create()
                {
                    CreateCalls++;
                    return _version4;
                }

                public Guid CreateVersion7()
                {
                    CreateVersion7Calls++;
                    return _version7;
                }
            }

            public static class GuidCreationProbe
            {
                public static bool Verify()
                {
                    var version4 = Guid.Parse("11111111-1111-4111-8111-111111111111");
                    var version7 = Guid.Parse("22222222-2222-7222-8222-222222222222");
                    var generator = new FakeGuidGenerator(version4, version7);

                    var randomId = OrderId.New(generator);
                    var orderedId = OrderId.NewVersion7(generator);

                    if (randomId.Value != version4 || orderedId.Value != version7)
                    {
                        return false;
                    }

                    if (generator.CreateCalls != 1 || generator.CreateVersion7Calls != 1)
                    {
                        return false;
                    }

                    try
                    {
                        _ = OrderId.New(null!);
                        return false;
                    }
                    catch (ArgumentNullException exception) when (exception.ParamName == "generator")
                    {
                    }

                    try
                    {
                        _ = OrderId.NewVersion7(null!);
                        return false;
                    }
                    catch (ArgumentNullException exception) when (exception.ParamName == "generator")
                    {
                    }

                    return true;
                }
            }
            """);

        var result = RunGenerator(compilation);
        Assert.Empty(result.GeneratorDiagnostics);
        Assert.Empty(result.OutputCompilation.GetDiagnostics().Where(static diagnostic => diagnostic.Severity == DiagnosticSeverity.Error));

        var generated = Assert.Single(result.GeneratedSources);
        Assert.Contains("generator.Create()", generated.Source, StringComparison.Ordinal);
        Assert.Contains("generator.CreateVersion7()", generated.Source, StringComparison.Ordinal);
        Assert.DoesNotContain("Guid.NewGuid", generated.Source, StringComparison.Ordinal);
        Assert.DoesNotContain("new global::TCJ.Core.Identifiers.GuidGenerator", generated.Source, StringComparison.Ordinal);
        Assert.DoesNotContain("ServiceProvider", generated.Source, StringComparison.Ordinal);

        var assembly = EmitAndLoad(result.OutputCompilation);
        var probeType = Assert.IsAssignableFrom<Type>(assembly.GetType("GuidCreationProbe"));
        var verify = Assert.IsAssignableFrom<MethodInfo>(probeType.GetMethod("Verify", BindingFlags.Public | BindingFlags.Static));

        Assert.True(Assert.IsType<bool>(verify.Invoke(null, null)));
    }

